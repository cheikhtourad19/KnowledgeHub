"""Router for PDF text extraction and CV summarization via Gemini"""
from fastapi import APIRouter, File, HTTPException, UploadFile, status
from pydantic import BaseModel, Field
from app.models import IndexSummaryRequest, IndexSummaryResponse
from app.services.pdf_service import pdf_extraction_service
from app.services.gemini_service import get_gemini_service
from app.services.text_chunking_service import text_chunking_service
from app.services.vector_db_cv_service import vector_db_cv_service
from app.config import settings
import logging
from io import BytesIO
from typing import Dict, Any

logger = logging.getLogger(__name__)

router = APIRouter(tags=["Text Processing"])


class ExtractTextResponse(BaseModel):
    success: bool
    extracted_text: str | None = None
    message: str | None = None


class SummarizeRequest(BaseModel):
    text: str = Field(..., min_length=1, description="Text to summarize")
    model: str = Field(default="gemini", description="Model to use (only gemini supported)")


class SummarizeResponse(BaseModel):
    success: bool
    summary: dict | None = None
    message: str | None = None


@router.post(
    "/extract-pdf-text",
    response_model=ExtractTextResponse,
    status_code=status.HTTP_200_OK,
    summary="Extract raw text from a PDF file",
    description="Accepts a PDF file upload, extracts all text using PyMuPDF, and returns the plain text content.",
)
async def extract_pdf_text(file: UploadFile = File(...)):
    max_bytes = settings.MAX_FILE_SIZE_MB * 1024 * 1024

    if file.content_type != "application/pdf":
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Only PDF files are accepted.",
        )

    file_bytes = await file.read()

    if not file_bytes:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Uploaded file is empty.",
        )

    if len(file_bytes) > max_bytes:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"File exceeds maximum size of {settings.MAX_FILE_SIZE_MB} MB.",
        )

    if not file_bytes.startswith(b"%PDF"):
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail="Invalid PDF file.",
        )

    try:
        raw_text = pdf_extraction_service.extract_text_from_bytes(BytesIO(file_bytes))
    except ValueError as e:
        raise HTTPException(
            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
            detail=f"Text extraction failed: {e}",
        )

    if not raw_text or len(raw_text.strip()) < settings.MIN_TEXT_LENGTH:
        return ExtractTextResponse(
            success=False,
            extracted_text=None,
            message="Could not extract readable text from PDF.",
        )

    logger.info(
        f"Extracted {len(raw_text)} characters from PDF '{file.filename}'"
    )

    return ExtractTextResponse(
        success=True,
        extracted_text=raw_text,
        message="Text extracted successfully.",
    )


@router.post(
    "/summarize-text",
    response_model=SummarizeResponse,
    status_code=status.HTTP_200_OK,
    summary="Summarize text using Gemini AI",
    description="Accepts raw text and returns a structured French CV summary generated by Gemini.",
)
async def summarize_text(request: SummarizeRequest):
    if not request.text or len(request.text.strip()) < settings.MIN_TEXT_LENGTH:
        return SummarizeResponse(
            success=False,
            summary=None,
            message="Input text is too short to summarize.",
        )

    try:
        gemini = get_gemini_service()
        summary = gemini.summarize_cv(request.text)
    except RuntimeError as e:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=str(e),
        )

    return SummarizeResponse(
        success=True,
        summary=summary,
        message="Summary generated successfully.",
    )


@router.post(
    "/index-summary",
    response_model=IndexSummaryResponse,
    status_code=status.HTTP_200_OK,
    summary="Index a CV summary (or any text) directly into ChromaDB",
    description="Takes summary text and metadata, chunks it, generates embeddings, and stores in ChromaDB. Used by resource-service after CV summarization.",
)
async def index_summary(request: IndexSummaryRequest):
    if not request.text or len(request.text.strip()) < settings.MIN_TEXT_LENGTH:
        return IndexSummaryResponse(
            success=False,
            chunks_indexed=0,
            message="Input text is too short to index.",
        )

    try:
        chunks = text_chunking_service.chunk_text(request.text)

        metadata = dict(request.metadata) if request.metadata else {}
        teacher_id = metadata.get("teacher_id", "unknown")
        text_id = f"cv_summary_{teacher_id}"

        chunks_indexed = await vector_db_cv_service.index_text(
            text_id=text_id,
            chunks=chunks,
            metadata=metadata,
        )

        logger.info(
            f"Indexed CV summary: text_id={text_id}, "
            f"chunks={chunks_indexed}, metadata={metadata}"
        )

        return IndexSummaryResponse(
            success=True,
            chunks_indexed=chunks_indexed,
            message=f"Successfully indexed summary with {chunks_indexed} chunks",
        )

    except ValueError as e:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=str(e),
        )
    except RuntimeError as e:
        raise HTTPException(
            status_code=status.HTTP_502_BAD_GATEWAY,
            detail=str(e),
        )
    except Exception as e:
        logger.error(f"Error indexing summary: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to index summary: {str(e)}",
        )


@router.delete(
    "/index-summary/{teacher_id}",
    status_code=status.HTTP_200_OK,
    summary="Delete all indexed CV summary vectors for a teacher",
    description="Removes all ChromaDB vectors where metadata matches teacher_id and document_type=cv_summary.",
)
async def delete_summary(teacher_id: int):
    try:
        metadata_filter: Dict[str, Any] = {
            "teacher_id": teacher_id,
            "document_type": "cv_summary",
        }
        chunks_deleted = await vector_db_cv_service.delete_by_metadata(metadata_filter)

        return {
            "success": True,
            "teacher_id": teacher_id,
            "chunks_deleted": chunks_deleted,
            "message": f"Deleted {chunks_deleted} summary chunks for teacher_id={teacher_id}",
        }

    except Exception as e:
        logger.error(f"Error deleting summary for teacher_id={teacher_id}: {e}")
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to delete summary: {str(e)}",
        )
